#include <cstddef>
#include <gtest/gtest.h>

extern "C" {
#include "vscp-rs485-protocol.h"
}

TEST(VscpRs485Protocol, supports_254_clients_and_8bit_nicknames)
{
  EXPECT_EQ(VSCP_RS485_MAX_CLIENTS, 254);
  EXPECT_EQ(VSCP_RS485_NICKNAME_SIZE, 1);
}

TEST(VscpRs485Protocol, defines_master_and_broadcast_nicknames)
{
  EXPECT_EQ(VSCP_RS485_MASTER_ID, 0x00);
  EXPECT_EQ(VSCP_RS485_BROADCAST_ID, 0xFF);
}

TEST(VscpRs485Protocol, defines_framing_bytes)
{
  EXPECT_EQ(VSCP_RS485_DLE, 0x10);
  EXPECT_EQ(VSCP_RS485_STX, 0x02);
  EXPECT_EQ(VSCP_RS485_ETX, 0x03);
}

TEST(VscpRs485Protocol, defines_parser_states)
{
  EXPECT_EQ(STATE_VSCP_RS485_WAIT_FOR_FRAME_START, 0);
  EXPECT_EQ(STATE_VSCP_RS485_WAIT_FOR_FRAME_END, 1);
  EXPECT_EQ(STATE_VSCP_RS485_FRAME_RECEIVED, 2);
}

TEST(VscpRs485Protocol, defines_frame_layout)
{
  EXPECT_EQ(VSCP_RS485_POS_FRAME_TYPE, 0);
  EXPECT_EQ(VSCP_RS485_POS_DESTINATION_NICKNAME, 1);
  EXPECT_EQ(VSCP_RS485_POS_SOURCE_NICKNAME, 2);
  EXPECT_EQ(VSCP_RS485_POS_SEQUENCE, 3);
  EXPECT_EQ(VSCP_RS485_POS_FLAGS, 4);
  EXPECT_EQ(VSCP_RS485_POS_FRAME_SIZE_PAYLOAD_MSB, 5);
  EXPECT_EQ(VSCP_RS485_POS_FRAME_SIZE_PAYLOAD_LSB, 6);
  EXPECT_EQ(VSCP_RS485_POS_FRAME_PAYLOAD, 7);
}

TEST(VscpRs485Protocol, defines_frame_types)
{
  EXPECT_EQ(VSCP_RS485_FRAME_TYPE_NOOP, 0);
  EXPECT_EQ(VSCP_RS485_FRAME_TYPE_POLL_REQUEST, 1);
  EXPECT_EQ(VSCP_RS485_FRAME_TYPE_POLL_RESPONSE, 2);
  EXPECT_EQ(VSCP_RS485_FRAME_TYPE_VSCP_EVENT, 3);
  EXPECT_EQ(VSCP_RS485_FRAME_TYPE_NO_EVENT, 4);
  EXPECT_EQ(VSCP_RS485_FRAME_TYPE_COMMAND, 5);
  EXPECT_EQ(VSCP_RS485_FRAME_TYPE_COMMAND_REPLY, 6);
  EXPECT_EQ(VSCP_RS485_FRAME_TYPE_ACK, 251);
  EXPECT_EQ(VSCP_RS485_FRAME_TYPE_NACK, 252);
  EXPECT_EQ(VSCP_RS485_FRAME_TYPE_ERROR, 253);
}

TEST(VscpRs485Protocol, defines_flags_and_commands)
{
  EXPECT_EQ(VSCP_RS485_FLAG_ENCRYPTED, 0x01);
  EXPECT_EQ(VSCP_RS485_FLAG_ACK_REQUEST, 0x02);
  EXPECT_EQ(VSCP_RS485_FLAG_RESERVED, 0xFC);

  EXPECT_EQ(VSCP_RS485_COMMAND_NOOP, 0);
  EXPECT_EQ(VSCP_RS485_COMMAND_POLL, 1);
  EXPECT_EQ(VSCP_RS485_COMMAND_SET_ENCRYPTION_NONE, 2);
  EXPECT_EQ(VSCP_RS485_COMMAND_SET_ENCRYPTION_AES128, 3);
}

TEST(VscpRs485Protocol, defines_errors_and_encryption_modes)
{
  EXPECT_EQ(VSCP_RS485_ERROR_CHECKSUM, 1);
  EXPECT_EQ(VSCP_RS485_ERROR_UNKNOWN_OPERATION, 2);
  EXPECT_EQ(VSCP_RS485_ERROR_INVALID_NICKNAME, 3);
  EXPECT_EQ(VSCP_RS485_ERROR_ENCRYPTION_FAILURE, 4);

  EXPECT_EQ(VSCP_RS485_ENCRYPTION_NONE, 0);
  EXPECT_EQ(VSCP_RS485_ENCRYPTION_AES128, 1);
}

TEST(VscpRs485Protocol, capability_struct_size_matches_macro)
{
  EXPECT_EQ(sizeof(vscp_rs485_caps), VSCP_RS485_CAPS_SIZE);
}

TEST(VscpRs485Protocol, capability_struct_is_one_byte_fields)
{
  vscp_rs485_caps caps{};
  caps.maxClients = VSCP_RS485_MAX_CLIENTS;
  caps.encryptionSupported = 1;
  caps.defaultEncryption = VSCP_RS485_ENCRYPTION_AES128;
  caps.reserved = 0;

  EXPECT_EQ(caps.maxClients, VSCP_RS485_MAX_CLIENTS);
  EXPECT_EQ(caps.encryptionSupported, 1);
  EXPECT_EQ(caps.defaultEncryption, VSCP_RS485_ENCRYPTION_AES128);
  EXPECT_EQ(caps.reserved, 0);
  EXPECT_EQ(sizeof(caps), 4u);
}
